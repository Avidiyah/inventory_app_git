SMR_XLSX_FILENAME = "smr27-audit-export.xlsx"
TAB_COLOR = "000000"

BEFORE, AFTER = "BEFORE", "AFTER"

# Every number in a snapshot's `totals`, plus the line count, as (label, key).
_NUMERIC = (
    ("MATERIAL LINES", None),
    ("MATERIALS TOTAL", "materials_total"),
    ("REAL MINUTES", "real_minutes"),
    ("SKILLED MINUTES", "skilled_minutes"),
    ("REAL BILLED MINUTES", "real_billed_minutes"),
    ("SKILLED BILLED MINUTES", "skilled_billed_minutes"),
    ("LABOR TOTAL", "labor_total"),
    ("TOTAL", "total"),
)
# The client's target and the gap to it (spec 2026-10-23-smr-target-match);
# all blank for an order without a Breakdown row.
_TARGET = (
    "MATERIALS +15% AFTER", "TARGET HOURS", "TARGET LABOR $", "TARGET MATERIAL $", "TARGET TOTAL",
    "GAP HOURS", "GAP MATERIAL $", "MATCHED", "TARGET IMPORTED AT",
)
# Keyed from paper (spec 2026-10-27-smr-paper-check); independent of a target.
_PAPER = ("PAPER CHECKED", "PAPER CHECKED AT", "PAPER CHECKED BY")
# The paper-correction figures (spec 2026-11-04). CHANGE is measured against
# the NetFacilities record before correction (the BEFORE billed figure).
_LINES = (
    "CORRECTED HOURS", "CORRECTED LABOR $", "CHANGE HOURS", "CHANGE $", "EXCLUDED HOURS",
    "LINES", "READINGS", "BLOCK VERSION", "BLOCK PASTED AT",
)
# Paper stage (spec 2026-11-06): where the paper stands, the Ready stamp,
# and whether every line is Belfor's.
_STAGE = ("STAGE", "READY AT", "READY BY", "BELFOR ONLY")
_BREAKDOWN_PREFIX = "BREAKDOWN "
_TRAIL = ("EDITED", "SMR IMPORTED AT", "BASELINE AT", "LAST EDITED AT", "LAST EDITED BY", "ARCHIVED AT")

MATERIAL_HEADERS = ("WORK ORDER", "PHASE", "ITEM", "BARCODE", "QUANTITY", "BILLABLE QUANTITY", "UNIT PRICE", "LINE TOTAL", "CREATED AT")
LABOR_HEADERS = ("WORK ORDER", "PHASE", "TECHNICIAN", "MINUTES", "RECORDED BY", "CREATED AT")
SESSION_HEADERS = ("WORK ORDER", "PHASE", "TECHNICIAN", "STARTED AT", "ENDED AT", "MINUTES", "AUTO CLOSED", "REVIEWED AT")
READING_HEADERS = ("WORK ORDER", "PRINTING", "WORK DATE", "HOURS AS READ", "RAW NOTE", "REVIEWER", "SOURCE", "LINES", "CREATED AT", "CREATED BY")
LINE_HEADERS = (
    "WORK ORDER", "LINE ID", "IMPORT KEY", "PRINTING", "WORK DATE", "DATE BASIS", "WEEK", "VENDOR", "WORKER", "ALIASES",
    "ALIAS ON PAPER", "HEADCOUNT", "HOURS EACH", "HOURS", "KIND", "REASON CODE", "STATUS", "EXCLUSION GROUND", "NOTE",
    "CREATED AT", "UPDATED AT",
)
HISTORY_HEADERS = ("WORK ORDER", "LINE ID", "IMPORT KEY", "FIELD", "OLD VALUE", "NEW VALUE", "REASON", "RUN ID", "EDITED AT", "EDITED BY")
BLOCK_HEADERS = ("WORK ORDER", "VERSION", "LATEST", "STALE", "GENERATED AT", "GENERATED BY", "PASTED AT", "PASTED BY", "LINES DIGEST", "TEXT")
WORKER_HEADERS = ("NAME", "VENDOR", "ALIASES", "ADMIN", "LINKED USER", "CREATED AT", "ARCHIVED AT")
# The import's history reason (`work_orders_smr_import.py`); anything else is free text.
_RUN_ID = re.compile(r"import [0-9a-f]{12}")


def _num(value) -> Optional[float]:
    """Snapshot numbers are strings (Decimal-safe JSON); Excel wants numbers."""
    if value is None:
        return None
    return float(Decimal(value)) if isinstance(value, str) else float(value)


def _when(value) -> Optional[datetime]:
    if value is None:
        return None
    parsed = datetime.fromisoformat(value) if isinstance(value, str) else value
    # openpyxl refuses tz-aware datetimes; the ISO text already says UTC.
    return parsed.replace(tzinfo=None)


def _source_columns(orders: Iterable[WorkOrder]) -> list[str]:
    """The sheet's own headers across every baseline, in sheet order."""
    seen: set[str] = set()
    for order in orders:
        seen.update(((order.smr_baseline or {}).get("source_row") or {}).keys())
    return smr.sheet_column_order(seen)


def _target_columns(orders: Iterable[WorkOrder]) -> list[str]:
    """The Breakdown sheet's headers across every target, in its own order."""
    seen: set[str] = set()
    for order in orders:
        seen.update(((order.smr_target or {}).get("source_row") or {}).keys())
    known = [c for c in smr.TARGET_SHEET_COLUMNS if c in seen]
    return known + sorted(c for c in seen if c not in smr.TARGET_SHEET_COLUMNS)


def _target_values(order: WorkOrder, current: dict) -> list:
    """`_TARGET` values for one order; a row of None without a target."""
    target = smr_service.target_for(order, current)
    if target is None:
        return [None] * len(_TARGET)
    return [
        _num(target.current_materials_total),
        _num(target.hours),
        _num(target.labor_total),
        _num(target.materials_total),
        _num(target.total),
        _num(target.gap_hours),
        _num(target.gap_materials_total),
        "YES" if target.matched else "NO",
        _when((order.smr_target or {}).get("imported_at")),
    ]


def _paper_values(order: WorkOrder) -> list:
    if order.smr_paper_checked_at is None:
        return [None] * len(_PAPER)
    who = order.smr_paper_checked_by
    return ["YES", _when(order.smr_paper_checked_at), who.full_name if who else None]


def _stage_values(order: WorkOrder) -> list:
    tile = smr_service.tile_for(order)
    return [
        tile.stage,
        _when(tile.ready.at) if tile.ready else None,
        tile.ready.by_name if tile.ready else None,
        "TRUE" if tile.belfor_only else "FALSE",
    ]


def _lines_values(order: WorkOrder, baseline: dict) -> list:
    """`_LINES` values for one order; the five figures blank without lines."""
    lines = smr.correction_lines(order)
    readings = len(order.smr_readings)
    if not lines:
        return [None] * 5 + [0, readings, None, None]
    charge = rules.lines_charge(lines)
    totals = baseline["totals"]
    hours, total = _num(charge.charged_hours), _num(charge.labor_total)
    before_hours = (_num(totals["real_billed_minutes"]) + _num(totals["skilled_billed_minutes"])) / 60
    block = lines_service.latest_block(order)
    return [
        hours, total, hours - before_hours, total - _num(totals["labor_total"]), _num(charge.excluded_hours),
        charge.count, readings,
        block.version if block else None, _when(block.pasted_at) if block else None,
    ]


# Operational-export columns the sheet already supplies by the same name.
_SHEET_OWNED = {"WORK ORDER", "LOCATION", "ASSIGNED TO", "SERVICE TYPE", "SCHEDULE DATE"}
_APP_HEADERS = [h for h in wo.EXPORT_HEADERS if h not in _SHEET_OWNED]


def _number_value(snap: dict, key: Optional[str]):
    return len(snap["material_lines"]) if key is None else snap["totals"][key]


def _last_edit(order: WorkOrder, baseline_at: Optional[datetime], names: dict) -> tuple[Optional[datetime], str]:
    """The latest labor entry or material line added after the baseline."""
    latest: Optional[datetime] = None
    who = ""
    for entry in order.labor_entries:
        if entry.created_at and (baseline_at is None or entry.created_at > baseline_at):
            if latest is None or entry.created_at > latest:
                latest, who = entry.created_at, (entry.recorded_by.full_name if entry.recorded_by else "")
    for line in order.items:
        if line.created_at and (baseline_at is None or line.created_at > baseline_at):
            if latest is None or line.created_at > latest:
                latest, who = line.created_at, names.get(line.created_by_id, "")
    return latest, who


def _orders_sheet(sheet: Worksheet, orders: list[WorkOrder], names: dict) -> None:
    source_columns = _source_columns(orders)
    target_columns = _target_columns(orders)
    headers = (
        source_columns
        + _APP_HEADERS
        + [f"{label} {phase}" for label, _ in _NUMERIC for phase in (BEFORE, AFTER, "DELTA")]
        + list(_TARGET)
        + list(_PAPER)
        + list(_LINES)
        + list(_STAGE)
        + [f"{_BREAKDOWN_PREFIX}{column}" for column in target_columns]
        + list(_TRAIL)
    )
    theme.setup_sheet(sheet, tab_color=TAB_COLOR, freeze="B2")
    theme.header_row(sheet, 1, headers)
    rows = []
    for order in orders:
        current = smr_service.current_snapshot(order)
        baseline = order.smr_baseline or current
        source = baseline.get("source_row") or {}
        baseline_at = _when(baseline.get("taken_at"))
        edited_at, edited_by = _last_edit(order, order.smr_imported_at, names)
        numbers = []
        for _, key in _NUMERIC:
            b, a = _num(_number_value(baseline, key)), _num(_number_value(current, key))
            numbers += [b, a, a - b]
        breakdown = (order.smr_target or {}).get("source_row") or {}
        rows.append(
            [source.get(column) for column in source_columns]
            + [value for header, value in zip(wo.EXPORT_HEADERS, wos.export_row(order)) if header not in _SHEET_OWNED]
            + numbers
            + _target_values(order, current)
            + _paper_values(order)
            + _lines_values(order, baseline)
            + _stage_values(order)
            + [breakdown.get(column) for column in target_columns]
            + [
                "YES" if smr.is_edited(order) else "NO",
                _when(order.smr_imported_at),
                baseline_at,
                _when(edited_at),
                edited_by,
                _when(order.archived_at),
            ]
        )
    theme.write_rows(sheet, 2, rows)


def _phase_rows(orders: list[WorkOrder], key: str, project) -> list[list]:
    rows: list[list] = []
    for order in orders:
        current = smr_service.current_snapshot(order)
        baseline = order.smr_baseline or current
        for phase, snap in ((BEFORE, baseline), (AFTER, current)):
            for record in snap[key]:
                rows.append([order.number, phase] + project(record))
    return rows


def _lines_sheet(sheet: Worksheet, headers: tuple[str, ...], rows: list[list]) -> None:
    theme.setup_sheet(sheet, tab_color=TAB_COLOR, freeze="C2")
    theme.header_row(sheet, 1, headers)
    theme.write_rows(sheet, 2, rows)


def _yes(flag) -> str:
    return "YES" if flag else "NO"


def _paper_sheets(workbook: Workbook, orders: list[WorkOrder], edits: list[SmrLineEdit],
                  workers: list[SmrWorker], names: dict) -> None:
    """The five paper-correction sheets. `smr_orders` already carries
    readings, lines (with worker) and blocks; edits and workers come in
    fetched, so nothing here touches the session."""
    lines = [
        (order, line) for order in orders
        for line in sorted(order.smr_lines, key=lambda l: (l.work_date is None, l.work_date or datetime.min.date(), l.created_at))
    ]
    readings = {reading.id: reading for order in orders for reading in order.smr_readings}
    line_count = Counter(line.reading_id for _, line in lines)
    _lines_sheet(workbook.create_sheet("Paper Readings"), READING_HEADERS, [
        [order.number, r.printing_no, r.work_date, _num(r.hours_as_read), r.raw_note, r.reviewer, r.source,
         line_count[r.id], _when(r.created_at), names.get(r.created_by_id)]
        for order in orders for r in order.smr_readings
    ])
    _lines_sheet(workbook.create_sheet("Labor Lines"), LINE_HEADERS, [
        [order.number, str(line.id), line.import_key,
         readings[line.reading_id].printing_no if line.reading_id in readings else None,
         line.work_date, line.date_basis, line.week, line.vendor,
         line.worker.display_name if line.worker else None,
         ", ".join(line.worker.aliases or []) if line.worker else None,
         line.alias_on_paper, line.headcount, _num(line.hours_each), _num(rules.line_hours(line)), line.kind,
         line.reason_code, line.status, line.exclusion_ground, line.note, _when(line.created_at), _when(line.updated_at)]
        for order, line in lines
    ])
    by_line = {line.id: (index, order.number, line.import_key) for index, (order, line) in enumerate(lines)}
    _lines_sheet(workbook.create_sheet("Line History"), HISTORY_HEADERS, [
        [by_line[edit.line_id][1], str(edit.line_id), by_line[edit.line_id][2], edit.field, edit.old_value,
         edit.new_value, edit.reason, edit.reason if edit.reason and _RUN_ID.fullmatch(edit.reason) else None,
         _when(edit.edited_at), names.get(edit.edited_by_id)]
        for edit in sorted(edits, key=lambda e: (by_line[e.line_id][0], e.edited_at))
    ])
    block_rows = []
    for order in orders:
        latest = lines_service.latest_block(order)
        for block in order.smr_blocks:
            is_latest = latest is not None and block.id == latest.id
            block_rows.append([
                order.number, block.version, _yes(is_latest), _yes(latest.stale) if is_latest else None,
                _when(block.generated_at), names.get(block.generated_by_id), _when(block.pasted_at),
                names.get(block.pasted_by_id), block.lines_digest, block.text,
            ])
    _lines_sheet(workbook.create_sheet("Correction Blocks"), BLOCK_HEADERS, block_rows)
    _lines_sheet(workbook.create_sheet("Workers"), WORKER_HEADERS, [
        [w.display_name, w.vendor, ", ".join(w.aliases or []), _yes(w.is_admin), names.get(w.user_id),
         _when(w.created_at), _when(w.archived_at)]
        for w in workers
    ])


def smr_workbook(db: Session) -> bytes:
    orders = smr_service.smr_orders(db)
    line_ids = [line.id for order in orders for line in order.smr_lines]
    edits = db.query(SmrLineEdit).filter(SmrLineEdit.line_id.in_(line_ids)).all() if line_ids else []
    workers = db.query(SmrWorker).order_by(SmrWorker.vendor, SmrWorker.display_name).all()
    user_ids = (
        {line.created_by_id for order in orders for line in order.items}
        | {reading.created_by_id for order in orders for reading in order.smr_readings}
        | {uid for order in orders for block in order.smr_blocks for uid in (block.generated_by_id, block.pasted_by_id)}
        | {edit.edited_by_id for edit in edits}
        | {worker.user_id for worker in workers}
    ) - {None}
    names = {
        user.id: user.full_name
        for user in db.query(User).filter(User.id.in_(user_ids)).all()
    } if user_ids else {}

    workbook = Workbook()
    orders_sheet = workbook.active
    orders_sheet.title = "Orders"
    _orders_sheet(orders_sheet, orders, names)

    _lines_sheet(
        workbook.create_sheet("Material Lines"), MATERIAL_HEADERS,
        _phase_rows(orders, "material_lines", lambda r: [
            r["item_name"], r["barcode"], _num(r["quantity"]), _num(r["billable_quantity"]),
            _num(r["unit_price"]), _num(r["line_total"]), _when(r["created_at"]),
        ]),
    )
    _lines_sheet(
        workbook.create_sheet("Labor Entries"), LABOR_HEADERS,
        _phase_rows(orders, "labor_entries", lambda r: [
            r["technician"], r["minutes"], r["recorded_by"], _when(r["created_at"]),
        ]),
    )
    _lines_sheet(
        workbook.create_sheet("Labor Sessions"), SESSION_HEADERS,
        _phase_rows(orders, "labor_sessions", lambda r: [
            r["technician"], _when(r["started_at"]), _when(r["ended_at"]), r["minutes"],
            "YES" if r["auto_closed"] else "NO", _when(r["reviewed_at"]),
        ]),
    )
    _paper_sheets(workbook, orders, edits, workers, names)

    buffer = io.BytesIO()
    workbook.save(buffer)
    return buffer.getvalue()
