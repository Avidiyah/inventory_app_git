"""The SMR27 audit workbook (spec 2026-10-23 §Export; paper record spec
2026-11-04 §Export).

Nine sheets. `Orders` is one row per SMR order: the vendor sheet's raw
columns, the operational export's columns, a BEFORE / AFTER / DELTA triple
for every number analytics will sum, the paper-correction figures, then the
audit trail. The three phase sheets carry one row per material line, labor
entry and labor session, each tagged `PHASE` = BEFORE (from the frozen
baseline) or AFTER (the live order through the same serializer), so the two
phases are column-identical. The five paper sheets are the correction record
itself: readings, lines, line history, every block version, workers.
Money and minutes are written as numbers, never strings."""

